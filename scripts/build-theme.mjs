// Generate color-only dark overrides from the shared styles so all views stay
// covered as components evolve. Layout and typography stay in the source CSS.
function hsl(hex){
  const raw=hex.slice(1),full=raw.length===3||raw.length===4?[...raw].map(c=>c+c).join(''):raw;
  const rgb=[0,2,4].map(i=>parseInt(full.slice(i,i+2),16)/255),max=Math.max(...rgb),min=Math.min(...rgb),delta=max-min,l=(max+min)/2;
  let h=0,s=0;
  if(delta){s=delta/(1-Math.abs(2*l-1));h=max===rgb[0]?((rgb[1]-rgb[2])/delta)%6:max===rgb[1]?(rgb[2]-rgb[0])/delta+2:(rgb[0]-rgb[1])/delta+4;h=(h*60+360)%360;}
  return {h,s,l,a:full.length===8?parseInt(full.slice(6),16)/255:1};
}
function recolor(hex,kind){
  const c=hsl(hex),h=c.s<.08?135:c.h,s=Math.min(c.s*.5,.19);
  let light;
  if(kind==='background')light=.105+(1-c.l)*.125;
  else if(kind==='border')light=.23+(1-c.l)*.06;
  else if(kind==='shadow')return `rgb(0 0 0 / ${Math.min(c.a,.4).toFixed(3)})`;
  else light=.91-c.l*.20;
  const alpha=c.a<1?` / ${c.a.toFixed(3)}`:'';
  return `hsl(${h.toFixed(0)} ${(s*100).toFixed(1)}% ${(light*100).toFixed(1)}%${alpha})`;
}
function splitSelectors(text){
  const selectors=[];let start=0,depth=0,quote='';
  for(let i=0;i<text.length;i++){
    const c=text[i];if(quote){if(c===quote&&text[i-1]!=='\\')quote='';continue;}
    if(c==='"'||c==="'"){quote=c;continue;}
    if(c==='('||c==='[')depth++;if(c===')'||c===']')depth--;
    if(c===','&&!depth){selectors.push(text.slice(start,i).trim());start=i+1;}
  }selectors.push(text.slice(start).trim());return selectors;
}
function prefix(selector){
  if(selector===':root')return '';
  if(selector.startsWith('html'))return selector.replace(/^html/,'html[data-theme="dark"]');
  return `html[data-theme="dark"] ${selector}`;
}
function rules(css){
  let result='',cursor=0;
  while(cursor<css.length){
    const open=css.indexOf('{',cursor);if(open<0)break;
    const selector=css.slice(cursor,open).trim();let close=open+1,depth=1,quote='';
    for(;close<css.length;close++){
      const c=css[close];if(quote){if(c===quote&&css[close-1]!=='\\')quote='';continue;}
      if(c==='"'||c==="'"){quote=c;continue;}if(c==='{')depth++;if(c==='}'&&!--depth)break;
    }
    const body=css.slice(open+1,close);cursor=close+1;
    if(selector.startsWith('@')){
      if(/^@(media|supports|layer|container)\b/.test(selector)){const nested=rules(body);if(nested)result+=`${selector}{${nested}}\n`;}
      continue;
    }
    const declarations=[];
    for(const statement of body.split(';')){
      const colon=statement.indexOf(':');if(colon<0)continue;
      const property=statement.slice(0,colon).trim(),value=statement.slice(colon+1).trim();
      if(!/^(color|background(?:-color|-image)?|border(?:-(?:top|bottom|left|right))?(?:-color)?|box-shadow|outline(?:-color)?|accent-color|scrollbar-color|fill|stroke)$/.test(property))continue;
      const kind=property.startsWith('background')?'background':property.startsWith('border')?'border':property==='box-shadow'?'shadow':'foreground';
      declarations.push(`${property}:${value.replace(/#[0-9a-f]{3,8}\b/gi,hex=>recolor(hex,kind))}`);
    }
    const selectors=splitSelectors(selector).map(prefix).filter(Boolean);
    if(selectors.length&&declarations.length)result+=`${selectors.join(',')}{${declarations.join(';')}}\n`;
  }return result;
}
